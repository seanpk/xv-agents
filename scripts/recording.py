#!/usr/bin/env python3
"""Turn a defect's recording into the first draft of its red test.

A recording is the better oracle for a defect: the failing path, the input, the
wrong result. This reads one and writes a test skeleton that replays the same
requests. Expected values come from the recording's `expected` field, which a
person states, never from running the code. Where a recording has no expected
value for the step that went wrong, the skeleton fails on purpose and says so;
the scenario agent fills it in from the scenario's words.

Reads:
  - an API sequence, JSON: {"steps": [{"request": {...}, "response": {...}, "expected": ...}]}
  - a HAR file (a browser's or a proxy's export)
  - a Playwright trace (.zip): the network part only; the actions are left to the agent

Usage:
  xv recording show <file>                       the steps, as JSON
  xv recording to-test <file> --lang python|playwright [--out <path>] [--name <name>] [--base-url <url>]
"""

import argparse
import json
import os
import re
import sys
import zipfile
from urllib.parse import urlparse

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from xvlib import XVError, die  # noqa: E402


def _body(text, mime=""):
    if text is None or text == "":
        return None
    if isinstance(text, (dict, list)):
        return text
    try:
        return json.loads(text)
    except (json.JSONDecodeError, TypeError):
        return text


def _path(url):
    u = urlparse(url)
    return u.path + (f"?{u.query}" if u.query else "") if u.scheme else url


def from_api_sequence(data):
    steps = []
    for s in data.get("steps", []):
        req, resp = s.get("request", {}), s.get("response", {})
        steps.append({"method": req.get("method", "GET").upper(), "path": req.get("path") or _path(req.get("url", "")),
                      "body": req.get("body"), "status": resp.get("status"), "response": resp.get("body"),
                      "expected": s.get("expected"), "has_expected": "expected" in s})
    return {"what": data.get("what", ""), "steps": steps}


def from_har(data):
    steps = []
    for e in data.get("log", {}).get("entries", []):
        req, resp = e.get("request", {}), e.get("response", {})
        content = resp.get("content", {})
        if content.get("mimeType", "").split(";")[0] not in ("application/json", "text/plain", ""):
            continue  # pages, scripts, images: the agent reads those in the browser
        steps.append({"method": req.get("method", "GET").upper(), "path": _path(req.get("url", "")),
                      "body": _body((req.get("postData") or {}).get("text")), "status": resp.get("status"),
                      "response": _body(content.get("text")), "expected": None, "has_expected": False})
    return {"what": data.get("log", {}).get("comment", ""), "steps": steps}


def from_trace(path):
    steps = []
    with zipfile.ZipFile(path) as z:
        names = [n for n in z.namelist() if n.endswith(".network")]
        for n in names:
            for line in z.read(n).decode("utf-8", "replace").splitlines():
                try:
                    ev = json.loads(line)
                except json.JSONDecodeError:
                    continue
                snap = ev.get("snapshot") if ev.get("type") == "resource-snapshot" else None
                if not snap:
                    continue
                req, resp = snap.get("request", {}), snap.get("response", {})
                mime = (resp.get("content") or {}).get("mimeType", "")
                if "json" not in mime:
                    continue
                steps.append({"method": req.get("method", "GET").upper(), "path": _path(req.get("url", "")),
                              "body": _body((req.get("postData") or {}).get("text")), "status": resp.get("status"),
                              "response": None, "expected": None, "has_expected": False})
    return {"what": "network requests from a Playwright trace; read the trace for the actions", "steps": steps}


def load(path):
    if path.endswith(".zip"):
        return from_trace(path)
    with open(path) as f:
        data = json.load(f)
    if "log" in data and "entries" in data.get("log", {}):
        return from_har(data)
    if "steps" in data:
        return from_api_sequence(data)
    raise XVError(f"{path} is not an API sequence, a HAR file, or a Playwright trace")


def _ident(text):
    words = re.findall(r"[a-z0-9]+", (text or "").lower())
    return "_".join(words[:8]) or "the_recorded_defect"


def to_python(rec, name, base_url=None):
    last = len(rec["steps"]) - 1
    lines = [
        "import json",
        "import unittest",
        "from urllib.error import HTTPError",
        "from urllib.request import Request, urlopen",
        "",
        "# Generated by `xv recording to-test` from a defect's recording. Edit it into the red:",
        "# start the app the way the existing tests do, and keep every expected value from the",
        "# recording or the scenario, never from running the code.",
        "",
        (f"BASE = {base_url!r}" if base_url else "BASE = None  # set in setUp, the way the existing tests start the app"),
        "",
        "",
        "def call(method, path, body=None):",
        "    data = json.dumps(body).encode() if body is not None else None",
        "    req = Request(BASE + path, data=data, method=method, headers={\"Content-Type\": \"application/json\"})",
        "    try:",
        "        with urlopen(req) as r:",
        "            return r.status, json.loads(r.read() or b\"null\")",
        "    except HTTPError as e:",
        "        return e.code, json.loads(e.read() or b\"null\")",
        "",
        "",
        f"class {''.join(w.title() for w in name.split('_'))}Test(unittest.TestCase):",
        f"    \"\"\"{rec['what'] or 'Replays the recorded defect.'}\"\"\"",
        "",
        f"    def test_{name}(self):",
    ]
    for i, s in enumerate(rec["steps"]):
        body = repr(s["body"]) if s["body"] is not None else "None"
        lines.append(f"        status, body = call({s['method']!r}, {s['path']!r}, {body})")
        if i < last or not s["has_expected"]:
            if s["status"] is not None:
                lines.append(f"        self.assertEqual(status, {s['status']!r})")
        if i == last:
            if s["has_expected"]:
                lines.append(f"        # the recording's expected result; it saw {s['response']!r}")
                lines.append(f"        self.assertEqual(body, {s['expected']!r})")
            else:
                lines.append(f"        # the recording saw {s['response']!r}, which is the defect")
                lines.append("        self.fail(\"write the expected result here, from the scenario's words\")")
    lines += ["", "", "if __name__ == \"__main__\":", "    unittest.main()", ""]
    return "\n".join(lines)


def to_playwright(rec, name):
    last = len(rec["steps"]) - 1
    lines = [
        "import { test, expect } from '@playwright/test';",
        "",
        "// Generated by `xv recording to-test` from a defect's recording. Edit it into the red.",
        "// Set baseURL in playwright.config. Every expected value comes from the recording or the",
        "// scenario, never from running the code.",
        "",
        f"test('{name.replace('_', ' ')}', async ({{ request }}) => {{",
    ]
    for i, s in enumerate(rec["steps"]):
        opts = f", {{ data: {json.dumps(s['body'])} }}" if s["body"] is not None else ""
        fn = s["method"].lower() if s["method"] in ("GET", "POST", "PUT", "PATCH", "DELETE") else "fetch"
        lines.append(f"  const r{i} = await request.{fn}('{s['path']}'{opts});")
        if (i < last or not s["has_expected"]) and s["status"] is not None:
            lines.append(f"  expect(r{i}.status()).toBe({s['status']});")
        if i == last:
            if s["has_expected"]:
                lines.append(f"  // the recording saw {json.dumps(s['response'])}")
                lines.append(f"  expect(await r{i}.json()).toEqual({json.dumps(s['expected'])});")
            else:
                lines.append(f"  // the recording saw {json.dumps(s['response'])}, which is the defect")
                lines.append("  test.fail(true, \"write the expected result here, from the scenario's words\");")
    lines += ["});", ""]
    return "\n".join(lines)


def main(argv=None):
    p = argparse.ArgumentParser(prog="xv recording", description=__doc__.split("\n")[0])
    sub = p.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("show")
    s.add_argument("file")
    t = sub.add_parser("to-test")
    t.add_argument("file")
    t.add_argument("--lang", choices=["python", "playwright"], required=True)
    t.add_argument("--out")
    t.add_argument("--name")
    t.add_argument("--base-url", help="for python: a running app's URL, instead of starting it in setUp")
    a = p.parse_args(argv)
    try:
        rec = load(a.file)
        if a.cmd == "show":
            print(json.dumps(rec, indent=2))
            return
        if not rec["steps"]:
            raise XVError("the recording has no requests this can replay; write the red by hand from it")
        name = a.name or _ident(rec["what"])
        text = to_python(rec, name, a.base_url) if a.lang == "python" else to_playwright(rec, name)
        if a.out:
            if os.path.exists(a.out):
                raise XVError(f"{a.out} exists; the red goes in a new file")
            os.makedirs(os.path.dirname(a.out) or ".", exist_ok=True)
            with open(a.out, "w") as f:
                f.write(text)
            print(a.out)
        else:
            sys.stdout.write(text)
    except XVError as e:
        die(str(e), 2)


if __name__ == "__main__":
    main()
