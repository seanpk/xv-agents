#!/usr/bin/env python3
"""Read the project layer against the shared core. Changes nothing.

  relaxations   project lines that read as relaxing the protected core (docs/core.md)
  overrides     harness files that would shadow a shared skill and stop its upgrades
  entries       every rules, standards and learnings entry, with the miss it came from
  drift         harness doc sentences the briefs rely on (docs/relies-on.md) that are gone

Usage: xv check [relaxations|overrides|entries|drift] [--json] [--offline]
Exit 1 when a relaxation or an unrecorded override is found.
"""

import argparse
import glob
import hashlib
import html
import json
import os
import re
import sys
import urllib.request

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from xvlib import XV_DIR, XVError, die, load_config, repo_root, worktrees_config  # noqa: E402

XV_HOME = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
AGENTS = ["watch", "forecaster", "scenario", "maker", "cleaner", "guardian", "listener"]
SKILLS = AGENTS + ["xv-slice", "xv-retro", "xv-promote", "xv-check", "xv-init"]

GUARDED = r"(record|wall|guardian|stop|stops|packet|review|baseline|scenario agent|two people|pitch|check)"
RELAX = [
    (re.compile(r"\b(without|no need (for|to)|skip(ping)?|don'?t (need|bother)|need not|not required|optional)\b"
                r"[^.\n]{0,50}\b" + GUARDED, re.I), "drops a guarded step"),
    (re.compile(r"\b(maker|cleaner|scenario agent|agent|agents|watch)\b[^.\n]{0,30}\b(may|can|should|is allowed to)\b"
                r"[^.\n]{0,20}\b(edit|change|delete|rewrite|merge|approve|rank|raise|accept|skip)\b[^.\n]{0,40}"
                r"\b(test|tests|budget|standard|standards|pull request|pr|change|queue|its own)", re.I),
     "lets an agent do what a may-not list forbids"),
    (re.compile(r"\bsame (context|session|agent)\b[^.\n]{0,60}\b(scenario|maker|cleaner|guardian|red|green)", re.I),
     "puts two agents in one context"),
    (re.compile(r"\b(turn|switch)(ed)? off\b[^.\n]{0,40}" + GUARDED + r"|\bdisable[ds]?\b[^.\n]{0,40}" + GUARDED, re.I),
     "turns off a check or a stop"),
    (re.compile(r"\b(auto-?merge|merge(s|d)? automatically|approve(s|d)? automatically|self-?approve)", re.I),
     "merges or approves without a person"),
]


def project_files(root):
    files = [os.path.join(root, XV_DIR, n) for n in
             ("rules.md", "standards.md", "learnings.md", "pitch.md", "picture.md", "config.yml")]
    files += sorted(glob.glob(os.path.join(root, XV_DIR, "decisions", "*.md")))
    return [f for f in files if os.path.exists(f)]


def relaxations(root):
    hits = []
    for path in project_files(root):
        rel = os.path.relpath(path, root)
        with open(path, encoding="utf-8", errors="replace") as f:
            for n, line in enumerate(f, 1):
                if line.lstrip().startswith(("#", "```")) and path.endswith(".yml"):
                    continue
                for rx, why in RELAX:
                    if rx.search(line):
                        hits.append({"where": f"{rel}:{n}", "line": line.strip()[:200], "why": why})
                        break
    config = load_config(root)
    if (config.get("wall") or {}).get("require_record") is False:
        hits.append({"where": f"{XV_DIR}/config.yml", "line": "wall.require_record: false",
                     "why": "lets a test move without a record in CI"})
    if ((config.get("seats") or {}).get("two_people") or "") == "solo":
        hits.append({"where": f"{XV_DIR}/config.yml", "line": "seats.two_people: solo", "declared": True,
                     "why": "solo: one person answers the two-person stops (declared, and allowed)"})
    for key in ("setup", "teardown"):
        cmd = worktrees_config(config).get(key)
        if cmd:
            hits.append({"where": f"{XV_DIR}/config.yml", "line": f"worktrees.{key}: {cmd}", "declared": True,
                         "why": f"runs a command in each slice's worktree ({key}; declared, and allowed)"})
    agents = config.get("agents") or {}
    if agents.get("scenario") == "session" and agents.get("maker") == "session":
        hits.append({"where": f"{XV_DIR}/config.yml", "line": "agents.scenario and agents.maker: session",
                     "why": "the scenario agent and the maker may share the person's context; check they run in separate subagents"})
    return hits


def skill_digest(name):
    path = os.path.join(XV_HOME, "skills", name, "SKILL.md")
    if not os.path.exists(path):
        return None
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()[:12]


GENERATED = re.compile(r"generated by `?xv adapt`? from skills/([\w-]+)/SKILL\.md \(([0-9a-f]{12})\)")


def installed_copy(folder, mark):
    """A copy `xv install --scope project` made: current, stale, or edited in this repo."""
    import install
    try:
        with open(mark) as f:
            m = json.load(f)
    except (OSError, json.JSONDecodeError):
        return "installed copy with an unreadable mark"
    if m.get("digest") != install.digest(folder):
        return "installed copy, edited in this repo: it no longer receives upgrades; record why in .xv/decisions"
    if m.get("version") != install.version():
        return f"installed copy from {m.get('version')}, stale: this xv is {install.version()}; run xv install --scope project"
    user = [f for _, f in install.user_folders() if os.path.lexists(os.path.join(f, m.get("skill", "")))]
    return "installed copy, current" + (f"; also installed for this person in {user[0]}, which wins in "
                                         "Claude Code" if user else "")


def overrides(root):
    found = []
    patterns = [".claude/agents/*.md", ".claude/skills/*/SKILL.md", ".opencode/agent/*.md", ".opencode/agents/*.md",
                ".opencode/prompts/*.md", ".cursor/rules/*", ".codex/agents/*", ".agents/skills/*/SKILL.md",
                ".github/agents/*.md"]
    decisions = ""
    for d in glob.glob(os.path.join(root, XV_DIR, "decisions", "*.md")):
        decisions += open(d, encoding="utf-8", errors="replace").read()
    for pat in patterns:
        for path in glob.glob(os.path.join(root, pat)):
            rel = os.path.relpath(path, root)
            parts = re.split(r"[/.]", rel)
            names = [s for s in SKILLS if s in parts or f"xv-{s}" in parts]
            if not names:
                continue
            text = open(path, encoding="utf-8", errors="replace").read()
            mark = os.path.join(os.path.dirname(path), ".xv-installed")
            if os.path.exists(mark):
                found.append({"file": rel, "skill": names[0], "kind": installed_copy(os.path.dirname(path), mark)})
                continue
            m = GENERATED.search(text)
            if m:
                current = skill_digest(m.group(1)) == m.group(2)
                found.append({"file": rel, "skill": m.group(1),
                              "kind": "generated, current" if current else "generated, stale: re-run xv adapt"})
                continue
            recorded = rel in decisions
            found.append({"file": rel, "skill": names[0],
                          "kind": "override, recorded in .xv/decisions" if recorded
                          else "override with no decision record: it shadows the shared skill and stops its upgrades"})
    return found


ENTRY = re.compile(r"^### (.+?)\n(.*?)(?=^### |^## |\Z)", re.S | re.M)


def parse_entries(path):
    text = open(path, encoding="utf-8", errors="replace").read()
    section = None
    out = []
    for block in re.split(r"(?=^## )", text, flags=re.M):
        head = block.splitlines()[0] if block.startswith("## ") else ""
        section = head[3:].strip() if head else section
        for title, rest in ENTRY.findall(block):
            if "<" in title and ">" in title:
                continue  # the template in the file's header
            fields = dict(re.findall(r"^- (\w+):\s*(.+)$", rest, re.M))
            seen = re.findall(r"([\w.-]+)@(\d{4}-\d{2}-\d{2})", fields.get("seen", ""))
            out.append({"file": os.path.basename(path), "section": section, "entry": title.strip(),
                        "linked": fields.get("adopts") or fields.get("shared"),
                        "added": fields.get("added", ""), "from": fields.get("from", ""),
                        "miss": fields.get("miss", ""), "seen": seen,
                        "repos": sorted({r for r, _ in seen})})
    return out


def entries(root):
    rows = []
    for name in ("rules.md", "standards.md", "learnings.md"):
        path = os.path.join(root, XV_DIR, name)
        if os.path.exists(path):
            rows += parse_entries(path)
    for r in rows:
        notes = []
        if not r["from"] or "xv-init" in r["from"] and not r["miss"]:
            notes.append("no slice: delete at the next retro")
        if r["file"] == "learnings.md" and r["section"] == "Open" and len(r["seen"]) >= 2:
            notes.append("seen twice: put its promotion in front of the person")
        if r.get("linked"):
            notes.append(f"linked to {r['linked']}: once a release carries it, delete this local copy")
        if len(r["repos"]) >= 2:
            notes.append("seen in two repos: a candidate for the shared skills (xv promote)")
        r["notes"] = notes
    return rows


def norm(text):
    return re.sub(r"\s+", " ", text).strip().lower()


def drift(offline=False):
    path = os.path.join(XV_HOME, "docs", "relies-on.md")
    items = []
    for line in open(path, encoding="utf-8"):
        m = re.match(r'^- (.+?) \| (https?://\S+) \| "(.+)"\s*$', line.strip())
        if m:
            items.append({"for": m.group(1), "url": m.group(2), "sentence": m.group(3)})
    if offline:
        return [dict(i, status="not checked (offline)") for i in items]
    pages = {}
    for i in items:
        if i["url"] not in pages:
            try:
                req = urllib.request.Request(i["url"], headers={"User-Agent": "xv-agents drift check"})
                raw = urllib.request.urlopen(req, timeout=30).read().decode("utf-8", "replace")
                raw = re.sub(r"<script.*?</script>|<style.*?</style>", " ", raw, flags=re.S)
                pages[i["url"]] = norm(html.unescape(re.sub(r"<[^>]+>", " ", raw)))
            except Exception as e:
                pages[i["url"]] = e
        page = pages[i["url"]]
        if isinstance(page, Exception):
            i["status"] = f"unreachable: {page}"
        else:
            i["status"] = "present" if norm(i["sentence"]) in page else "gone"
    return items


def main(argv=None):
    p = argparse.ArgumentParser(prog="xv check", description=__doc__.split("\n")[0])
    p.add_argument("what", nargs="?", default="all", choices=["all", "relaxations", "overrides", "entries", "drift"])
    p.add_argument("--json", action="store_true")
    p.add_argument("--offline", action="store_true", help="skip the drift fetch")
    p.add_argument("--report", help="write the drifted sentences as Markdown to this file; exit 1 if any")
    a = p.parse_args(argv)
    try:
        root = repo_root()
        res = {}
        if a.what in ("all", "relaxations"):
            res["relaxations"] = relaxations(root)
        if a.what in ("all", "overrides"):
            res["overrides"] = overrides(root)
        if a.what in ("all", "entries"):
            res["entries"] = entries(root)
        if a.what in ("all", "drift"):
            res["drift"] = drift(a.offline)
    except XVError as e:
        die(str(e), 2)
    bad = [h for h in res.get("relaxations", []) if not h.get("declared")] or \
        [o for o in res.get("overrides", []) if o["kind"].startswith("override with no")]
    gone = [d for d in res.get("drift", []) if d["status"] != "present"]
    if a.report:
        with open(a.report, "w") as f:
            f.write("".join(f"- {d['status']}: \"{d['sentence']}\" at {d['url']} ({d['for']})\n" for d in gone))
        bad = bad or gone
    if a.json:
        print(json.dumps(res, indent=2, ensure_ascii=False))
    else:
        for h in res.get("relaxations", []):
            print(f"relaxation  {h['where']}: {h['why']}\n            {h['line']}")
        for o in res.get("overrides", []):
            print(f"override    {o['file']} ({o['skill']}): {o['kind']}")
        for e in res.get("entries", []):
            note = f"  <- {'; '.join(e['notes'])}" if e["notes"] else ""
            print(f"entry       {e['file']}: {e['entry']}  (from {e['from'] or 'nowhere'}){note}")
        for d in res.get("drift", []):
            if d["status"] != "present":
                print(f"drift       {d['status']}: \"{d['sentence'][:70]}\" at {d['url']} ({d['for']})")
        if "drift" in res and all(d["status"] == "present" for d in res["drift"]):
            print(f"drift       all {len(res['drift'])} sentences present")
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
