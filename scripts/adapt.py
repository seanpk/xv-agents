#!/usr/bin/env python3
"""Optional: write a harness's own subagent files from the skills.

The skills are the source. These files are generated, carry a marker with the
skill's digest, and are named `xv-<agent>` so they never shadow a skill of the
same name. `xv check overrides` lists a generated file as current or stale, and
any other file with an agent's name as an override. Re-run after an upgrade.

A team needs these only to run a step as a subagent in the person's own
session (`agents.<step>: session`). `xv step` does not use them.

Usage: xv adapt claude|opencode [--agents maker,guardian,...]
"""

import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from check import AGENTS, skill_digest  # noqa: E402
from xvlib import XVError, die, repo_root, split_front_matter  # noqa: E402

HOME = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def skill(name):
    with open(os.path.join(HOME, "skills", name, "SKILL.md")) as f:
        return split_front_matter(f.read())


def marker(name):
    return (f"<!-- generated by xv adapt from skills/{name}/SKILL.md ({skill_digest(name)}). "
            "Do not edit: change the skill, or copy it under a new name and record why in .xv/decisions/. -->")


def write_claude(root, name):
    meta, body = skill(name)
    path = os.path.join(root, ".claude", "agents", f"xv-{name}.md")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(f"---\nname: xv-{name}\ndescription: {json.dumps(meta.get('description', ''))}\n---\n\n"
                f"{marker(name)}\n\n{body.strip()}\n")
    return os.path.relpath(path, root)


def write_opencode(root, name):
    meta, body = skill(name)
    path = os.path.join(root, ".opencode", "agent", f"xv-{name}.md")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(f"---\ndescription: {json.dumps(meta.get('description', ''))}\nmode: subagent\n---\n\n"
                f"{marker(name)}\n\n{body.strip()}\n")
    return os.path.relpath(path, root)


def main(argv=None):
    p = argparse.ArgumentParser(prog="xv adapt", description=__doc__.split("\n")[0])
    p.add_argument("harness", choices=["claude", "opencode"])
    p.add_argument("--agents", default=",".join(a for a in AGENTS if a != "watch"))
    a = p.parse_args(argv)
    try:
        root = repo_root()
        names = [n.strip() for n in a.agents.split(",") if n.strip()]
        unknown = [n for n in names if n not in AGENTS]
        if unknown:
            raise XVError(f"no agent skill {unknown}; one of {AGENTS}")
        fn = write_claude if a.harness == "claude" else write_opencode
        for n in names:
            print(fn(root, n))
    except XVError as e:
        die(str(e), 2)


if __name__ == "__main__":
    main()
